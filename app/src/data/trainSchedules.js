function expandRunsOn(arr) {
  const set = new Set();
  for (const d of arr) {
    if (d === "M" || d === "W" || d === "F") set.add(d);
    else if (d === "T") {
      set.add("T"); // Tuesday
      set.add("Th"); // Thursday
    } else if (d === "S") {
      set.add("Sa"); // Saturday
      set.add("Su"); // Sunday
    } else {
      set.add(d);
    }
  }
  return Array.from(set);
}

